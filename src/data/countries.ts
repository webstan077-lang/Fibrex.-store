export const DEFAULT_COUNTRY = COUNTRIES_CURRENCIES[0]; // United States USD ($)

export function getCountryByCode(code: string): CountryCurrencyConfig {
  return (
    COUNTRIES_CURRENCIES.find(
      (c) =>
        c.countryCode.toLowerCase() === code.toLowerCase() ||
        c.currencyCode.toLowerCase() === code.toLowerCase()
    ) || DEFAULT_COUNTRY
  );
}
